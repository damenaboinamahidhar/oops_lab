class DATA_OPERATIONS
{
public static void main(String args[])
{
int a=100;
int b=5;
System.out.println(a+b);
System.out.println(a-b);
System.out.println(a/b);
System.out.println(a%b);
a++;
System.out.println(a);
b--;
System.out.println(b);
System.out.println(a>b);
System.out.println(a<b);
System.out.println(a<=b);
System.out.println(a>=b);
System.out.println(a!=b);
System.out.println(a==b);
System.out.println(a>50 && b<50);
System.out.println(a>120 || b<120);
System.out.println(!(a==b));
}
}

